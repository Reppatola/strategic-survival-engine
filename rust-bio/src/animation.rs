// ============================================================
// ТАБЛИЦА АНИМАЦИИ
//
// Каждая поза — свои параметры движения.
// Скорость движения и частота шагов связаны физически.
//
//   phase_rate = step_freq × π
//
// Один цикл = 2 шага = 2π. Один шаг = π.
// ============================================================

pub struct AnimParams {
    pub pose: u32,
    pub step_freq: f32,   // шагов в секунду
    pub step_length: f32, // длина шага, см
    pub arm_amp: f32,     // амплитуда качания рук (sin)
    pub leg_amp: f32,     // амплитуда качания ног (sin)
}

// ============================================================
// ЗНАЧЕНИЯ ПО ФИЗИОЛОГИИ ЧЕЛОВЕКА
//
//   STANDING  = 0  — стоит
//   WALKING   = 1  — 1.4 м/с, 2.0 шага/с, шаг 70 см
//   RUNNING   = 2  — 5.0 м/с, 3.3 шага/с, шаг 150 см
//   SNEAKING  = 3  — 0.5 м/с, 1.0 шага/с, шаг 50 см
// ============================================================
pub const ANIM_TABLE: &[AnimParams] = &[
    AnimParams {
        pose: 0,
        step_freq: 0.0,
        step_length: 0.0,
        arm_amp: 0.00,
        leg_amp: 0.00,
    },
    AnimParams {
        pose: 1,
        step_freq: 2.0,
        step_length: 70.0,
        arm_amp: 0.22,
        leg_amp: 0.22,
    },
    AnimParams {
        pose: 2,
        step_freq: 3.3,
        step_length: 150.0,
        arm_amp: 0.42,
        leg_amp: 0.42,
    },
    AnimParams {
        pose: 3,
        step_freq: 1.0,
        step_length: 50.0,
        arm_amp: 0.12,
        leg_amp: 0.12,
    },
];

// ============================================================
// Получить параметры по ID позы
// ============================================================
pub fn find_anim(pose: u32) -> Option<&'static AnimParams> {
    ANIM_TABLE.iter().find(|a| a.pose == pose)
}

// ============================================================
// Частота роста фазы — радиан в секунду
//
//   phase_rate = step_freq × π
// ============================================================
pub fn phase_rate_for(pose: u32) -> f32 {
    match find_anim(pose) {
        Some(a) => a.step_freq * std::f32::consts::PI,
        None => 0.0,
    }
}

// ============================================================
// Амплитуда для рук и ног
// ============================================================
pub fn amplitudes_for(pose: u32) -> (f32, f32) {
    match find_anim(pose) {
        Some(a) => (a.arm_amp, a.leg_amp),
        None => (0.0, 0.0),
    }
}
