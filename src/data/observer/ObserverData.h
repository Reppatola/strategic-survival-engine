#ifndef SSE_DATA_OBSERVER_OBSERVERDATA_H
#define SSE_DATA_OBSERVER_OBSERVERDATA_H

namespace SSE::Observer {

// ============================================================
// ДАННЫЕ НАБЛЮДАТЕЛЯ
//
// Наблюдатель — НЕ на герое.
// Наблюдатель — НА ВЫСОТЕ над героем.
//
// 1 см = 1 px. Все размеры в сантиметрах.
//
// Вариант B: высота 1000 см = 10 м.
// ============================================================

struct ObserverData {
    // Позиция наблюдателя
    float height_cm   = 1000.0f;   // высота над землёй
    float look_x_cm   = 0.0f;      // смещение взгляда по X
    float look_y_cm   = 0.0f;      // смещение взгляда по Y

    // Поле зрения (в см, потому что 1 см = 1 px)
    float view_core_cm = 200.0f;   // зона чёткости (2 м)
    float view_fade_cm = 500.0f;   // граница размытия (5 м)
    float view_max_cm  = 800.0f;   // граница зрения (8 м)

    // Масштаб отображения (зависит от высоты)
    // При height = 1000 см → scale = 1.0 (1 см = 1 px на экране)
    // При height = 500 см  → scale = 2.0 (приближение)
    // При height = 2000 см → scale = 0.5 (отдаление)
    float scale() const {
        return 1000.0f / height_cm;
    }
};

// ============================================================
// СТАНДАРТНЫЙ НАБЛЮДАТЕЛЬ (Вариант B)
// ============================================================
inline constexpr ObserverData STANDARD_OBSERVER = {
    1000.0f,    // высота 10 м
    0.0f,       // взгляд прямо
    0.0f,
    200.0f,     // R_CORE = 2 м
    500.0f,     // R_FADE = 5 м
    800.0f      // R_MAX  = 8 м
};

} // namespace SSE::Observer

#endif
