#ifndef SSE_DATA_CHARACTERS_SLICE_H
#define SSE_DATA_CHARACTERS_SLICE_H

namespace SSE::Characters {

// ============================================================
// СРЕЗЫ — единицы измерения формы тела
//
// Данные тела описываются СРЕЗАМИ в двух направлениях:
//   HSlice — горизонтальный срез (на высоте Z)
//   VSlice — вертикальный срез (на позиции X)
//
// Все размеры в САНТИМЕТРАХ. 1 см = 1 пиксель.
// ============================================================

// ------------------------------------------------------------
// ГОРИЗОНТАЛЬНЫЙ СРЕЗ — «что на этой высоте»
// ------------------------------------------------------------
struct HSlice {
    float z;           // высота среза (см, от земли)
    float width;       // ширина (по X), см
    float depth;       // глубина (по Y), см
    float offset_x;    // смещение центра по X, см
    float offset_y;    // смещение центра по Y, см
};

// ------------------------------------------------------------
// ВЕРТИКАЛЬНЫЙ СРЕЗ — «что на этой позиции влево-вправо»
// ------------------------------------------------------------
struct VSlice {
    float x;           // позиция по X (см, от центра тела)
    float height;      // высота (по Z), см
    float depth;       // глубина (по Y), см
    float offset_z;    // смещение центра по Z, см
    float offset_y;    // смещение центра по Y, см
};

} // namespace SSE::Characters

#endif
